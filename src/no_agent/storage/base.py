"""
存储接口

框架只依赖这两个协议。默认实现：
  - FileSkillStore：技能存文件（可 git 管理）
  - SqlRunStore：运行记录存 SQL（SQLite / Postgres / MySQL，任意 SQLAlchemy URL）
使用者可以实现自己的版本（如技能存 S3、运行记录写入已有数据仓库），传给 Agent(skill_store=..., run_store=...)。
"""

from __future__ import annotations

from pathlib import Path
from typing import TYPE_CHECKING, Any, Literal, Protocol, runtime_checkable

if TYPE_CHECKING:
    from no_agent.skills.models import Permissions, Review, Skill, TestCase
    from no_agent.storage.sql import Run

# 存储结构版本：变更结构时 +1 并提供迁移
SKILL_SCHEMA_VERSION = 2  # 技能目录格式（1：manifest.json + vN.py；2：SKILL.md 格式）
RUNS_SCHEMA_VERSION = 1  # 运行记录库（迁移见 storage/sql.py 的 MIGRATIONS）
SCHEMA_VERSION = SKILL_SCHEMA_VERSION  # 兼容旧名


@runtime_checkable
class SkillStore(Protocol):
    def reload(self) -> None: ...
    def list(self, include_retired: bool = False) -> list[Skill]: ...
    def get(self, skill_id: str) -> Skill | None: ...
    def script(self, skill_id: str, version: int | None = None) -> str: ...
    def layer(self, skill_id: str) -> Literal["local", "shared"]: ...
    def path(self, skill_id: str) -> Path: ...  # 技能目录（读取 SKILL.md 等）
    def install(self, src: Path, *, overwrite: bool = False) -> Skill: ...

    def create(
        self, skill: Skill, script: str, *, reason: str, pass_rate: float | None = None, shadow: bool = False,
        review: Review | None = None,
    ) -> Skill: ...
    def add_version(
        self, skill_id: str, script: str, *, reason: str, pass_rate: float | None, activate: bool = True,
        review: Review | None = None, params_schema: dict[str, Any] | None = None, permissions: Permissions | None = None,
    ) -> Skill: ...
    def approve_review(self, skill_id: str, version: int, *, shadow: bool, comment: str = "") -> Skill: ...
    def reject_review(self, skill_id: str, version: int, reason: str = "审查未通过") -> Skill: ...
    def promote(self, skill_id: str) -> Skill: ...
    def reject_shadow(self, skill_id: str, reason: str) -> Skill: ...
    def save_shadow(self, skill: Skill) -> None: ...
    def set_active(self, skill_id: str, version: int) -> Skill: ...
    def set_status(self, skill_id: str, status: str) -> Skill: ...
    def add_test(self, skill: Skill, case: TestCase, max_cases: int) -> None: ...
    def save(self, skill: Skill) -> None: ...
    def save_stats(self, skill: Skill) -> None: ...
    def delete(self, skill_id: str) -> None: ...


@runtime_checkable
class RunStore(Protocol):
    def save(self, run: Run) -> Run: ...
    def get(self, run_id: str) -> Run | None: ...
    def list(self, limit: int = 50, skill_id: str | None = None) -> list[Run]: ...
    def distill_candidates(self, limit: int = 200) -> list[Run]: ...
